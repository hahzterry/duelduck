interface DdpointsToggleProps {
  isActive: boolean;
  onChange: (val: boolean) => void;
}

export const DdpointsToggle = memo(
  ({ isActive, onChange }: DdpointsToggleProps) => {
    const [particles, setParticles] = useState<number[]>([]);

    const handleClick = useCallback(() => {
      const next = !isActive;

      onChange(next);

      if (next) {
        const id = Date.now();

        setParticles([id]);
        setTimeout(() => {
          setParticles((prev) => prev.filter((p) => p !== id));
        }, ANIMATION_DURATION);
      }
    }, [isActive, onChange]);

    const particleData = useMemo(
      () =>
        particles.map((id) => ({
          id,
          items: Array.from({ length: PARTICLE_COUNT }, (_, i) => {
            const angle =
              ((360 / PARTICLE_COUNT) * i + (Math.random() * 30 - 15)) *
              (Math.PI / 180);
            const dist = 36 + Math.random() * 20;

            return {
              key: i,
              style: {
                '--tx': `${Math.cos(angle) * dist}px`,
                '--ty': `${Math.sin(angle) * dist}px`,
                '--delay': `${Math.random() * 80}ms`,
                '--size': `${12 + Math.random() * 6}px`,
                '--rot': `${Math.random() * 360}deg`,
              } as React.CSSProperties,
            };
          }),
        })),
      [particles],
    );

    return (
      <div
        className={cx(styles.toggle, {
          [`${styles['toggle--active']}`]: isActive,
        })}
        onClick={handleClick}
      >
        <div className={styles.toggle__icon}>
          {isActive ? <DuckIcon /> : <DdpDisabledIcon />}
        </div>

        {particleData.map((burst) => (
          <div key={burst.id} className={styles.particles}>
            {burst.items.map((p) => (
              <span key={p.key} className={styles.particle} style={p.style}>
                <MiniDuck />
              </span>
            ))}
          </div>
        ))}
      </div>
    );
  },
);

DdpointsToggle.displayName = 'DdpointsToggle';
